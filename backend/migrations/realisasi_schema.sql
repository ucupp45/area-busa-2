CREATE TABLE IF NOT EXISTS realisasi_identitas (
    id INT AUTO_INCREMENT PRIMARY KEY,
    kualitas VARCHAR(100),
    no_barcode VARCHAR(100),
    tanggal DATE,
    no_spk VARCHAR(100),
    nama_operator VARCHAR(100),
    shift VARCHAR(50),
    grup VARCHAR(50),
    asal_p DECIMAL(10,2),
    asal_l DECIMAL(10,2),
    asal_t DECIMAL(10,2),
    asal_qty INT,
    keterangan_kondisi TEXT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS realisasi_vertical (
    id INT AUTO_INCREMENT PRIMARY KEY,
    identitas_id INT,
    no_mesin VARCHAR(50),
    hasil_p DECIMAL(10,2),
    hasil_l DECIMAL(10,2),
    hasil_t DECIMAL(10,2),
    hasil_qty INT,
    waste_samping_p DECIMAL(10,2),
    waste_samping_l DECIMAL(10,2),
    waste_samping_t DECIMAL(10,2),
    waste_samping_qty INT,
    waste_dpn_blk_p DECIMAL(10,2),
    waste_dpn_blk_l DECIMAL(10,2),
    waste_dpn_blk_t DECIMAL(10,2),
    waste_dpn_blk_qty INT,
    sisa_p DECIMAL(10,2),
    sisa_l DECIMAL(10,2),
    sisa_t DECIMAL(10,2),
    sisa_qty INT,
    sisa_keterangan TEXT,
    dt_kode VARCHAR(50),
    dt_jam_awal TIME,
    dt_jam_akhir TIME,
    dt_keterangan TEXT,
    FOREIGN KEY (identitas_id) REFERENCES realisasi_identitas(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS realisasi_carousel (
    id INT AUTO_INCREMENT PRIMARY KEY,
    identitas_id INT,
    no_mesin VARCHAR(50),
    tipe_mesin VARCHAR(50) DEFAULT 'Horizontal',
    no_disk VARCHAR(100),
    no_wo VARCHAR(100),
    keterangan TEXT,
    hasil_p DECIMAL(10,2),
    hasil_l DECIMAL(10,2),
    hasil_t DECIMAL(10,2),
    hasil_qty INT,
    status VARCHAR(20) DEFAULT 'OK',
    alasan_reject TEXT,
    waste_kulit_t DECIMAL(10,2),
    waste_kulit_qty INT,
    sispot_p DECIMAL(10,2),
    sispot_l DECIMAL(10,2),
    sispot_t DECIMAL(10,2),
    sispot_qty INT,
    sispot_keterangan TEXT,
    waste_potong_t DECIMAL(10,2),
    waste_potong_qty INT,
    waste_produksi_t DECIMAL(10,2),
    waste_produksi_qty INT,
    dt_kode VARCHAR(50),
    dt_jam_awal TIME,
    dt_jam_akhir TIME,
    dt_keterangan TEXT,
    FOREIGN KEY (identitas_id) REFERENCES realisasi_identitas(id) ON DELETE CASCADE
);
