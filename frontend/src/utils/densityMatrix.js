export const getDensityFromMatrix = (kualitasStr) => {
  if (!kualitasStr) return 0;
  
  // Cari kecocokan exact di matriks (case-insensitive)
  const exactMatch = densityMatrixData.find(
    (item) => item.kode_asli.toLowerCase() === String(kualitasStr).toLowerCase().trim()
  );
  
  if (exactMatch) {
    return exactMatch.nilai_angka;
  }
  
  // Fallback: Cari menggunakan regex jika tidak ditemukan di matriks
  const match = String(kualitasStr).match(/\d+/);
  return match ? Number(match[0]) : 0;
};
